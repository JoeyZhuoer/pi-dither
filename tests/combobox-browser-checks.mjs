// Reusable real-DOM checks: call in an isolated browser fixture, never a live desktop.
export async function checkComboboxBrowser({ installComboboxes, syncCombobox }) {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const tick = () => new Promise(resolve => setTimeout(resolve, 0));
  const root = document.createElement('form'); root.addEventListener('submit', event => event.preventDefault()); document.body.append(root);
  root.innerHTML = '<label>Model <select name="model"><option value="a">Alpha</option><option disabled>Blocked</option><option value="b">Beta</option><option value="c">Charlie</option></select></label>';
  const select = root.querySelector('select'); let changes = 0;
  select.addEventListener('change', () => changes++);
  const api = installComboboxes(document);
  assert(installComboboxes(document) === api, 'document installation is idempotent');
  const button = root.querySelector('[role=combobox]');
  const key = k => button.dispatchEvent(new KeyboardEvent('keydown', { key: k, bubbles: true, cancelable: true }));
  const list = () => document.getElementById(button.getAttribute('aria-controls'));
  assert(button.getAttribute('aria-label') === 'Model', 'wrapped label name');
  button.focus(); button.click(); key('ArrowDown');
  assert(select.value === 'a', 'navigation is tentative');
  assert(button.getAttribute('aria-activedescendant').endsWith('-2'), 'disabled options skipped');
  key('Escape'); assert(select.value === 'a' && changes === 0 && list().hidden, 'escape cancels');
  key(' '); key('End'); key('Enter');
  assert(select.value === 'c' && changes === 1 && document.activeElement === button, 'commit changes exactly once and retains focus');
  assert(new FormData(root).get('model') === 'c', 'native form name/value semantics preserved');
  button.click(); key('Enter'); assert(changes === 1, 'unchanged commit is silent');
  select.value = 'b'; assert(button.textContent === 'Beta', 'programmatic value sync');
  select.selectedIndex = 0; assert(button.textContent === 'Alpha', 'programmatic index sync');
  button.click(); key('c'); key('Enter'); assert(select.value === 'c', 'typeahead');
  button.click(); key('Home'); key('Tab'); assert(select.value === 'c' && list().hidden, 'tab cancels tentative navigation');
  button.click(); document.body.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })); assert(list().hidden, 'outside pointer closes');
  select.disabled = true; await tick(); assert(button.disabled, 'disabled sync');
  select.disabled = false; await tick();
  const fieldset = document.createElement('fieldset'), label = select.parentElement; root.append(fieldset); fieldset.append(label);
  fieldset.disabled = true; await tick(); assert(button.disabled, 'inherited fieldset disability');
  fieldset.disabled = false; await tick(); assert(!button.disabled, 'fieldset re-enables the trigger');
  fieldset.before(label); fieldset.remove();
  const option = document.createElement('option'); option.value = 'safe'; option.textContent = '<img src=x onerror=alert(1)>';
  select.append(option); await tick(); select.value = 'safe';
  assert(button.textContent === option.textContent && !list().querySelector('img'), 'safe option text and dynamic insertion');
  button.click();
  list().querySelector('[data-index="0"]').click(); assert(select.value === 'a', 'pointer selection');
  for (let i = 0; i < 150; i++) select.add(new Option('Long model '.repeat(12) + i, String(i)));
  await tick(); button.click();
  const rect = list().getBoundingClientRect();
  assert(rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight, 'popup clamped to viewport');
  const before = document.activeElement; syncCombobox(select); assert(document.activeElement === before, 'sync never moves focus');
  root.hidden = true; await tick(); assert(list().hidden, 'hidden owner closes popup'); root.hidden = false;
  const dynamic = document.createElement('select'); dynamic.add(new Option('Dynamic', 'd')); root.append(dynamic); await tick();
  assert(root.querySelectorAll('[role=combobox]').length === 2, 'dynamic control enhanced');
  dynamic.remove(); await tick(); assert(root.querySelectorAll('[role=combobox]').length === 1, 'removed control cleaned up');
  const host = select.parentElement;
  host.replaceChildren(select); await tick();
  assert(select.nextElementSibling === button && button.isConnected, 'reconstruction restores the accessible trigger');
  const moved = document.createElement('div'); root.append(moved); moved.append(select); api.refresh(); await tick();
  assert(select.nextElementSibling === button && button.parentElement === moved, 'reparenting moves the trigger with its select');
  assert(root.querySelectorAll('[role=combobox]').length === 1, 'repair does not duplicate controls');
  select.replaceChildren(); await tick(); assert(button.disabled && button.textContent === 'No options', 'empty state');
  select.multiple = true; await tick();
  assert(!root.querySelector('[role=combobox]') && !select.classList.contains('pi-combobox-native') && select.tabIndex === 0, 'multi-select retains usable native fallback');
  select.multiple = false; api.refresh();
  assert(root.querySelector('[role=combobox]') && select.classList.contains('pi-combobox-native'), 'explicit refresh can enhance a restored single select');
  api.destroy(); assert(!root.querySelector('[role=combobox]') && !document.querySelector('[role=listbox]'), 'teardown removes UI');
  assert(!select.classList.contains('pi-combobox-native') && !select.hasAttribute('aria-hidden'), 'native restored');
  root.remove();
  return 'keyboard, cancel, typeahead, labels, safe text, pointer, viewport, dynamic state, focus and teardown passed';
}
